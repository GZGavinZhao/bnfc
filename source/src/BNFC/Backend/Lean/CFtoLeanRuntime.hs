{-# LANGUAGE OverloadedStrings #-}

{- |
Module      : BNFC.Backend.Lean.CFtoLeanRuntime
Description : Generates the language-independent parser runtime for the Lean
              backend.

The runtime provides:

  * @Token@ — the token type produced by the lexer.
  * @ParseError@ / @ParseResult@ — error reporting.
  * The 'Parser' monad: a function from a token stream to either
    @ParseError@ or a value plus the remaining stream.
  * Combinators: 'pure', 'bind', 'orElse', 'attempt', 'many', 'sepBy',
    'expectKeyword', 'expectSymbol', 'satisfyToken', 'eof' …

The generated file is parameterised only by what the generated code
imports; it is identical for every grammar.
-}

module BNFC.Backend.Lean.CFtoLeanRuntime ( runtimeContent ) where

runtimeContent :: String -> String
runtimeContent _runtimeMod = unlines
  [ "/-! Hand-written, dependency-free runtime for parsers generated by BNFC."
  , "    The runtime is intentionally minimal: it provides a token type,"
  , "    a parser monad with backtracking on failure that does not consume"
  , "    input, and the small handful of combinators needed by the generated"
  , "    parser code. -/"
  , ""
  , "namespace BNFC"
  , ""
  , "/-- A source position tracked by the lexer. -/"
  , "structure Position where"
  , "  line : Nat := 1"
  , "  col  : Nat := 1"
  , "  deriving Repr, Inhabited, BEq"
  , ""
  , "instance : ToString Position where"
  , "  toString p := s!\"{p.line}:{p.col}\""
  , ""
  , "/-- A token: a discriminator plus the source text. -/"
  , "inductive TokenKind where"
  , "  /-- A reserved word or punctuation symbol; the payload is the raw text. -/"
  , "  | keyword  : String → TokenKind"
  , "  /-- An identifier (matched as `Ident` in the grammar). -/"
  , "  | ident    : String → TokenKind"
  , "  /-- An integer literal. -/"
  , "  | intLit   : Int → TokenKind"
  , "  /-- A floating-point literal. -/"
  , "  | floatLit : Float → TokenKind"
  , "  /-- A string literal (already unescaped). -/"
  , "  | strLit   : String → TokenKind"
  , "  /-- A character literal. -/"
  , "  | charLit  : Char → TokenKind"
  , "  /-- A user-defined token (regex pragma).  Carries the token's category"
  , "      name and the matched lexeme. -/"
  , "  | userTok  : (cat : String) → (lexeme : String) → TokenKind"
  , "  deriving Repr, Inhabited"
  , ""
  , "structure Token where"
  , "  kind : TokenKind"
  , "  pos  : Position"
  , "  deriving Repr, Inhabited"
  , ""
  , "instance : ToString TokenKind where"
  , "  toString"
  , "    | .keyword k    => k"
  , "    | .ident s      => s"
  , "    | .intLit n     => toString n"
  , "    | .floatLit x   => toString x"
  , "    | .strLit s     => \"\\\"\" ++ s ++ \"\\\"\""
  , "    | .charLit c    => \"'\" ++ c.toString ++ \"'\""
  , "    | .userTok _ s  => s"
  , ""
  , "instance : ToString Token where"
  , "  toString t := s!\"{t.pos}: {t.kind}\""
  , ""
  , "/-- A parse error: position, expectation, and what was actually seen. -/"
  , "structure ParseError where"
  , "  pos     : Position"
  , "  message : String"
  , "  deriving Repr, Inhabited"
  , ""
  , "instance : ToString ParseError where"
  , "  toString e := s!\"parse error at {e.pos}: {e.message}\""
  , ""
  , "/-- A parser is a function from a token stream to an `Except` of value-plus-rest. -/"
  , "abbrev Parser (α : Type) := List Token → Except ParseError (α × List Token)"
  , ""
  , "/-! ## Regex AST + matcher for user-defined `token` pragmas."
  , ""
  , "    BNFC's `token X (pattern)` pragmas are compiled by the emitter into"
  , "    closed `BNFC.Reg` literals; the lexer then runs `Reg.matchPrefix`"
  , "    against each of them at every input position and picks the longest"
  , "    match.  The `Reg` constructors mirror BNFC's Haskell `Reg` ADT"
  , "    (`BNFC.Abs.Reg`) one-to-one.  `RMinus` (regex difference, `A - B`)"
  , "    is folded back into a plain `A` match — BNFC's grammars almost never"
  , "    use it in practice, and the cases that matter (e.g. excluding a"
  , "    keyword from an identifier-shaped token) are handled at the lexer"
  , "    level via the reserved-word check below."
  , "-/"
  , ""
  , "inductive Reg : Type where"
  , "  | eps    : Reg                       -- ε"
  , "  | char   : Char → Reg                -- 'c'"
  , "  | alts   : List Char → Reg           -- [\"abc\"] character class"
  , "  | seqs   : String → Reg              -- {\"abc\"} literal sequence"
  , "  | digit  : Reg                       -- builtin: 0-9"
  , "  | letter : Reg                       -- builtin: a-zA-Z"
  , "  | upper  : Reg                       -- builtin: A-Z"
  , "  | lower  : Reg                       -- builtin: a-z"
  , "  | anyCh  : Reg                       -- builtin: any single character"
  , "  | seq    : Reg → Reg → Reg           -- A B"
  , "  | alt    : Reg → Reg → Reg           -- A | B"
  , "  | star   : Reg → Reg                 -- A*"
  , "  | plus   : Reg → Reg                 -- A+"
  , "  | opt    : Reg → Reg                 -- A?"
  , "  | minus  : Reg → Reg → Reg           -- A - B  (treated as A; see header)"
  , "  deriving Inhabited"
  , ""
  , "/-- Greedy zero-or-more, consuming as much input as possible.  Stops"
  , "    on the first failed iteration *or* on an empty-match iteration"
  , "    (which would otherwise loop forever for patterns like `(eps)*`)."
  , "-/"
  , "private partial def starGreedy (matchOne : List Char → Option (List Char × List Char))"
  , "    : List Char → List Char → List Char × List Char"
  , "  | [],   acc => (acc, [])"
  , "  | cs,   acc =>"
  , "      match matchOne cs with"
  , "      | none            => (acc, cs)"
  , "      | some ([],    _) => (acc, cs)   -- empty match: avoid infinite loop"
  , "      | some (lex,   r) => starGreedy matchOne r (acc ++ lex)"
  , ""
  , "/-- Match the longest possible prefix of `cs` against `r`.  Returns the"
  , "    matched characters and the remaining input on success; `none` if no"
  , "    match.  All recursive structure is bounded by the input length"
  , "    (with the empty-match guard inside `starGreedy`), so this is total"
  , "    in practice; we declare it `partial` only to avoid a manual"
  , "    termination proof. -/"
  , "partial def Reg.matchPrefix : Reg → List Char → Option (List Char × List Char)"
  , "  | .eps,        cs            => some ([], cs)"
  , "  | .char _,     []            => none"
  , "  | .char c,     c' :: cs      => if c == c' then some ([c'], cs) else none"
  , "  | .alts _,     []            => none"
  , "  | .alts s,     c :: cs       => if s.contains c then some ([c], cs) else none"
  , "  | .seqs s,     cs            =>"
  , "      let lits := s.toList"
  , "      let rec go : List Char → List Char → Option (List Char)"
  , "        | [],         rest        => some rest"
  , "        | _ :: _,     []          => none"
  , "        | a :: as,    b :: rest   => if a == b then go as rest else none"
  , "      match go lits cs with"
  , "      | some rest => some (lits, rest)"
  , "      | none      => none"
  , "  | .digit,      []            => none"
  , "  | .digit,      c :: cs       => if c.isDigit then some ([c], cs) else none"
  , "  | .letter,     []            => none"
  , "  | .letter,     c :: cs       => if c.isAlpha then some ([c], cs) else none"
  , "  | .upper,      []            => none"
  , "  | .upper,      c :: cs       => if c.isUpper then some ([c], cs) else none"
  , "  | .lower,      []            => none"
  , "  | .lower,      c :: cs       => if c.isLower then some ([c], cs) else none"
  , "  | .anyCh,      []            => none"
  , "  | .anyCh,      c :: cs       => some ([c], cs)"
  , "  | .seq a b,    cs            =>"
  , "      match Reg.matchPrefix a cs with"
  , "      | none            => none"
  , "      | some (m1, r1)   =>"
  , "          match Reg.matchPrefix b r1 with"
  , "          | none            => none"
  , "          | some (m2, r2)   => some (m1 ++ m2, r2)"
  , "  | .alt a b,    cs            =>"
  , "      match Reg.matchPrefix a cs with"
  , "      | some r          => some r"
  , "      | none            => Reg.matchPrefix b cs"
  , "  | .star a,     cs            =>"
  , "      let (m, r) := starGreedy (Reg.matchPrefix a) cs []"
  , "      some (m, r)"
  , "  | .plus a,     cs            =>"
  , "      match Reg.matchPrefix a cs with"
  , "      | none            => none"
  , "      | some (m1, r1)   =>"
  , "          let (m2, r2) := starGreedy (Reg.matchPrefix a) r1 []"
  , "          some (m1 ++ m2, r2)"
  , "  | .opt a,      cs            =>"
  , "      match Reg.matchPrefix a cs with"
  , "      | some r          => some r"
  , "      | none            => some ([], cs)"
  , "  | .minus a _,  cs            =>"
  , "      -- Difference is treated as a plain `A` match; see the header"
  , "      -- comment for the rationale."
  , "      Reg.matchPrefix a cs"
  , ""
  , "/-- Try each `(category, regex)` pair against `cs`, returning the longest"
  , "    successful match (with the matched category, lexeme, and remainder)."
  , "    Ties on length are broken by *declaration order* in the input list,"
  , "    matching BNFC's convention that earlier `token` pragmas have priority. -/"
  , "def matchUserToks (regs : List (String × Reg))"
  , "    (cs : List Char) : Option (String × String × List Char) :="
  , "  let rec go : List (String × Reg)"
  , "       → Option (String × String × List Char × Nat)"
  , "       → Option (String × String × List Char × Nat)"
  , "    | [],            best => best"
  , "    | (cat, r) :: rest, best =>"
  , "        match Reg.matchPrefix r cs with"
  , "        | none             => go rest best"
  , "        | some (lex, cs')  =>"
  , "            let cand := (cat, String.ofList lex, cs', lex.length)"
  , "            match best with"
  , "            | none                  => go rest (some cand)"
  , "            | some (_, _, _, bestN) =>"
  , "                if lex.length > bestN then go rest (some cand)"
  , "                else                       go rest best"
  , "  (go regs none).map (fun (cat, lex, cs', _) => (cat, lex, cs'))"
  , ""
  , "namespace Parser"
  , ""
  , "/-- The position used to report end-of-input errors. -/"
  , "private def endOfInputPos : Position := { line := 0, col := 0 }"
  , ""
  , "@[inline] def pure {α : Type} (x : α) : Parser α := fun toks => Except.ok (x, toks)"
  , ""
  , "@[inline] def fail {α : Type} (pos : Position) (msg : String) : Parser α :="
  , "  fun _ => Except.error { pos := pos, message := msg }"
  , ""
  , "@[inline] def bind {α β : Type} (p : Parser α) (f : α → Parser β) : Parser β := fun toks =>"
  , "  match p toks with"
  , "  | .ok (x, rest) => f x rest"
  , "  | .error e      => .error e"
  , ""
  , "instance : Monad Parser where"
  , "  pure := Parser.pure"
  , "  bind := Parser.bind"
  , ""
  , "/-- Try `p`, and if it fails *without consuming input* try `q` instead."
  , "    A parser is considered to have consumed input if the remaining stream"
  , "    differs in length after the failure. -/"
  , "def orElse {α : Type} (p : Parser α) (q : Unit → Parser α) : Parser α := fun toks =>"
  , "  match p toks with"
  , "  | .ok r          => .ok r"
  , "  | .error _       => (q ()) toks"
  , ""
  , "instance : OrElse (Parser α) where"
  , "  orElse := Parser.orElse"
  , ""
  , "/-- Run `p`; on failure rewind so the next alternative sees the original input. -/"
  , "def attempt {α : Type} (p : Parser α) : Parser α := fun toks =>"
  , "  match p toks with"
  , "  | .ok r    => .ok r"
  , "  | .error _ => .error { pos := endOfInputPos, message := \"backtrack\" }"
  , ""
  , "/-- Look at the next token without consuming it. -/"
  , "def peek? : Parser (Option Token) := fun toks =>"
  , "  match toks with"
  , "  | []      => .ok (none, [])"
  , "  | t :: _  => .ok (some t, toks)"
  , ""
  , "/-- Consume a token that satisfies `p`. -/"
  , "def satisfy (p : TokenKind → Bool) (expected : String) : Parser Token := fun toks =>"
  , "  match toks with"
  , "  | []     => .error { pos := endOfInputPos, message := s!\"expected {expected}, got end of input\" }"
  , "  | t :: rest =>"
  , "      if p t.kind then .ok (t, rest)"
  , "      else .error { pos := t.pos, message := s!\"expected {expected}, got {t.kind}\" }"
  , ""
  , "/-- Consume a specific keyword/symbol. -/"
  , "def expectKeyword (kw : String) : Parser Unit := do"
  , "  let _ ← satisfy (fun k => match k with | .keyword s => s == kw | _ => false) s!\"`{kw}`\""
  , "  Parser.pure ()"
  , ""
  , "/-- Consume an `Ident` token, returning its lexeme. -/"
  , "def expectIdent : Parser String := fun toks =>"
  , "  match toks with"
  , "  | []        => .error { pos := endOfInputPos, message := \"expected identifier, got end of input\" }"
  , "  | t :: rest => match t.kind with"
  , "    | .ident s => .ok (s, rest)"
  , "    | k        => .error { pos := t.pos, message := s!\"expected identifier, got {k}\" }"
  , ""
  , "def expectIntLit : Parser Int := fun toks =>"
  , "  match toks with"
  , "  | []        => .error { pos := endOfInputPos, message := \"expected integer literal, got end of input\" }"
  , "  | t :: rest => match t.kind with"
  , "    | .intLit n => .ok (n, rest)"
  , "    | k         => .error { pos := t.pos, message := s!\"expected integer literal, got {k}\" }"
  , ""
  , "def expectFloatLit : Parser Float := fun toks =>"
  , "  match toks with"
  , "  | []        => .error { pos := endOfInputPos, message := \"expected float literal, got end of input\" }"
  , "  | t :: rest => match t.kind with"
  , "    | .floatLit x => .ok (x, rest)"
  , "    | k           => .error { pos := t.pos, message := s!\"expected float literal, got {k}\" }"
  , ""
  , "def expectStringLit : Parser String := fun toks =>"
  , "  match toks with"
  , "  | []        => .error { pos := endOfInputPos, message := \"expected string literal, got end of input\" }"
  , "  | t :: rest => match t.kind with"
  , "    | .strLit s => .ok (s, rest)"
  , "    | k         => .error { pos := t.pos, message := s!\"expected string literal, got {k}\" }"
  , ""
  , "def expectCharLit : Parser Char := fun toks =>"
  , "  match toks with"
  , "  | []        => .error { pos := endOfInputPos, message := \"expected char literal, got end of input\" }"
  , "  | t :: rest => match t.kind with"
  , "    | .charLit c => .ok (c, rest)"
  , "    | k          => .error { pos := t.pos, message := s!\"expected char literal, got {k}\" }"
  , ""
  , "/-- Consume a user-defined token of the given category, returning its lexeme. -/"
  , "def expectUserTok (cat : String) : Parser String := fun toks =>"
  , "  match toks with"
  , "  | []        => .error { pos := endOfInputPos, message := s!\"expected {cat}, got end of input\" }"
  , "  | t :: rest => match t.kind with"
  , "    | .userTok c s => if c == cat then .ok (s, rest)"
  , "                      else .error { pos := t.pos, message := s!\"expected {cat}, got {c}\" }"
  , "    | k            => .error { pos := t.pos, message := s!\"expected {cat}, got {k}\" }"
  , ""
  , "/-- Succeed iff there are no more tokens. -/"
  , "def eof : Parser Unit := fun toks =>"
  , "  match toks with"
  , "  | []     => .ok ((), [])"
  , "  | t :: _ => .error { pos := t.pos, message := s!\"expected end of input, got {t.kind}\" }"
  , ""
  , "/-- Zero or more applications of `p`.  Stops when `p` fails *without"
  , "    consuming input*. -/"
  , "partial def many {α : Type} (p : Parser α) : Parser (List α) := fun toks =>"
  , "  match p toks with"
  , "  | .ok (x, rest) =>"
  , "      if rest.length < toks.length then"
  , "        match many p rest with"
  , "        | .ok (xs, rest') => .ok (x :: xs, rest')"
  , "        | .error e        => .error e"
  , "      else .ok ([x], rest)  -- one application made progress at end of input"
  , "  | .error _      => .ok ([], toks)"
  , ""
  , "/-- One or more applications of `p`. -/"
  , "def many1 {α : Type} (p : Parser α) : Parser (List α) := do"
  , "  let x ← p"
  , "  let xs ← many p"
  , "  Parser.pure (x :: xs)"
  , ""
  , "/-- `p` separated by `sep`, possibly empty. -/"
  , "partial def sepBy {α β : Type} (p : Parser α) (sep : Parser β) : Parser (List α) := fun toks =>"
  , "  match p toks with"
  , "  | .error _      => .ok ([], toks)"
  , "  | .ok (x, rest) =>"
  , "      let rec loop (acc : List α) (cur : List Token) : Except ParseError (List α × List Token) :="
  , "        match sep cur with"
  , "        | .error _ => .ok (acc.reverse, cur)"
  , "        | .ok (_, after_sep) =>"
  , "            match p after_sep with"
  , "            | .ok (y, after_p) => loop (y :: acc) after_p"
  , "            | .error e         => .error e"
  , "      loop [x] rest"
  , ""
  , "/-- `p` separated by `sep`, at least one element. -/"
  , "def sepBy1 {α β : Type} (p : Parser α) (sep : Parser β) : Parser (List α) := do"
  , "  let x ← p"
  , "  let xs ← many (do let _ ← sep; p)"
  , "  Parser.pure (x :: xs)"
  , ""
  , "/-- Run a parser and require it to consume the entire input. -/"
  , "def run {α : Type} (p : Parser α) (toks : List Token) : Except ParseError α :="
  , "  match p toks with"
  , "  | .ok (x, []) => .ok x"
  , "  | .ok (_, t :: _) => .error { pos := t.pos, message := s!\"unexpected `{t.kind}` after parse\" }"
  , "  | .error e        => .error e"
  , ""
  , "end Parser"
  , "end BNFC"
  ]
